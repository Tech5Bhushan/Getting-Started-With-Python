# Day 10 - String Methods in Python

text = "Getting Started With Python"

# upper()
print(text.upper())

# lower()
print(text.lower())

# title()
message = "getting started with python"
print(message.title())

# strip()
language = "   Python   "
print(language.strip())

# replace()
sentence = "I am learning Java"
print(sentence.replace("Java", "Python"))

# split()
languages = "Python,Java,C++"
print(languages.split(","))

# find()
message = "Learning Python"
print(message.find("Python"))

# count()
word = "banana"
print(word.count("a"))