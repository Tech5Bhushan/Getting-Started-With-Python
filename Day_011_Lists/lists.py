# Day 11 - Introduction to Lists

# Creating a List
languages = ["Python", "Java", "C++"]

print(languages)

# Accessing elements
print(languages[0])
print(languages[1])
print(languages[2])

# Negative indexing
print(languages[-1])
print(languages[-2])

# Changing an element
languages[1] = "JavaScript"

print(languages)

# Number of elements
print(len(languages))


# List with different data types
person = ["Bhushan", 34, 5.9, True]

print(person)


# Duplicate values
skills = ["Python", "CANoe", "Python"]

print(skills)